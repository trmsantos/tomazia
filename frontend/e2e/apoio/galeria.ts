/**
 * As dimensões físicas de um JPEG, lidas dos marcadores `SOF0`/`SOF2` —
 * sem decodificar um só píxel. É a técnica que o 16.5 pede: "lê os
 * marcadores SOF do JPEG", para provar o lado maior e a orientação sem
 * depender de nenhuma biblioteca de imagem no lado do teste.
 *
 * Devolve `null` quando não é um JPEG (sem `SOI`) ou quando não encontra
 * nenhum marcador `SOF` — os dois casos são "não consegui ler", nunca
 * "zero por zero".
 */
export function lerDimensoesDoJpeg(bytes: Buffer): { largura: number; altura: number } | null {
  if (bytes.length < 4 || bytes[0] !== 0xff || bytes[1] !== 0xd8) return null;

  let offset = 2;
  while (offset + 4 <= bytes.length) {
    if (bytes[offset] !== 0xff) {
      offset += 1;
      continue;
    }
    const marcador = bytes[offset + 1];
    if (marcador === 0xd8 || marcador === 0xd9) {
      offset += 2;
      continue;
    }
    if (marcador !== undefined && marcador >= 0xd0 && marcador <= 0xd7) {
      offset += 2;
      continue;
    }
    const tamanho = ((bytes[offset + 2] ?? 0) << 8) | (bytes[offset + 3] ?? 0);
    const eSOF =
      marcador !== undefined &&
      marcador >= 0xc0 &&
      marcador <= 0xcf &&
      marcador !== 0xc4 &&
      marcador !== 0xc8 &&
      marcador !== 0xcc;
    if (eSOF) {
      const altura = ((bytes[offset + 5] ?? 0) << 8) | (bytes[offset + 6] ?? 0);
      const largura = ((bytes[offset + 7] ?? 0) << 8) | (bytes[offset + 8] ?? 0);
      return { largura, altura };
    }
    offset += 2 + tamanho;
  }
  return null;
}

/** O cabeçalho (texto) e os dados (bytes) de uma parte do `multipart/form-data`. */
export type ParteDoMultipart = { cabecalho: string; dados: Buffer };

/**
 * A parte de um corpo `multipart/form-data` cujo campo se chama `nomeDoCampo`
 * — o cabeçalho `Content-Disposition`/`Content-Type` da própria parte, e os
 * bytes a seguir, até à fronteira seguinte. Lê a fronteira do próprio
 * `Content-Type` do pedido, nunca à mão: uma fronteira escrita de memória
 * neste ficheiro divergia da que o browser gerou, e o teste deixava de
 * encontrar parte nenhuma, calado.
 *
 * O `cabecalho` da parte é o que dá acesso ao `Content-Type` **do
 * ficheiro** — distinto do `Content-Type` do pedido inteiro (que é sempre
 * `multipart/form-data; boundary=…`). É assim que se prova que um HEIC
 * chega convertido: o `Content-Type` da parte nunca é `image/heic`.
 */
export function extrairParteDoMultipart(
  corpo: Buffer,
  contentType: string,
  nomeDoCampo: string,
): ParteDoMultipart | null {
  const fronteira = /boundary=(?:"([^"]+)"|([^;]+))/.exec(contentType);
  const valor = fronteira?.[1] ?? fronteira?.[2];
  if (valor === undefined) return null;

  const delimitador = Buffer.from(`--${valor}`);
  const partes = dividirPor(corpo, delimitador);

  for (const parte of partes) {
    const cabecalhoFim = parte.indexOf("\r\n\r\n");
    if (cabecalhoFim === -1) continue;
    const cabecalho = parte.subarray(0, cabecalhoFim).toString("latin1");
    if (!cabecalho.includes(`name="${nomeDoCampo}"`)) continue;
    // +4 salta o \r\n\r\n; -2 tira o \r\n antes da fronteira seguinte.
    const dados = parte.subarray(cabecalhoFim + 4, parte.length - 2);
    return { cabecalho, dados };
  }
  return null;
}

function dividirPor(corpo: Buffer, delimitador: Buffer): Buffer[] {
  const partes: Buffer[] = [];
  let inicio = 0;
  for (;;) {
    const proximo = corpo.indexOf(delimitador, inicio);
    if (proximo === -1) {
      if (inicio < corpo.length) partes.push(corpo.subarray(inicio));
      break;
    }
    if (proximo > inicio) partes.push(corpo.subarray(inicio, proximo));
    inicio = proximo + delimitador.length;
  }
  return partes;
}

