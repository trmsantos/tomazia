/** Finge `/media/<ficheiro>` com um PNG válido, para qualquer nome pedido. */
export async function fingirOMedia(pagina: Page): Promise<void> {
  await pagina.route(ROTA_DE_MEDIA, async (rota) => {
    await rota.fulfill({ status: 200, contentType: "image/png", body: PNG_MINIMO });
  });
}

export type RespostaDaGaleria = { tipo: "galeria"; corpo: Galeria } | { tipo: "falha" };

async function cumprirGaleria(rota: Route, resposta: RespostaDaGaleria): Promise<void> {
  if (resposta.tipo === "falha") {
    await rota.abort("failed");
    return;
  }
  await rota.fulfill({
    status: 200,
    contentType: "application/json",
    body: JSON.stringify(resposta.corpo),
  });
}

/** Finge `GET /api/galeria` e `/media/**` (ver `fingirOMedia`). Chamar antes do `goto`. */
export async function fingirAGaleria(pagina: Page, corpo: Galeria = SEM_FOTOS): Promise<void> {
  await fingirOMedia(pagina);
  await pagina.route(ROTA_DA_GALERIA, async (rota) => {
    await cumprirGaleria(rota, { tipo: "galeria", corpo });
  });
}

/** O que o `POST /fotos` fingido viu de um pedido. */
export type PedidoDeEnvioObservado = {
  metodo: string;
  contentType: string;
  corpo: Buffer;
};

export type RespostaDoEnvio =
  | { tipo: "sucesso" }
  | {
      tipo: "erro";
      estado: number;
      corpo: Record<string, unknown>;
      cabecalhos?: Record<string, string>;
    };

/**
 * Finge `POST /api/fotos` e devolve o array onde cada pedido interceptado
 * fica registado — o método, o `Content-Type` (para confirmar a fronteira
 * do multipart) e o corpo em bytes (para ler o ficheiro lá dentro).
 */
export async function fingirOEnvioDeFotos(
  pagina: Page,
  responder: () => RespostaDoEnvio = () => ({ tipo: "sucesso" }),
): Promise<PedidoDeEnvioObservado[]> {
  const pedidos: PedidoDeEnvioObservado[] = [];

  await pagina.route(ROTA_DE_FOTOS, async (rota) => {
    const pedido = rota.request();
    const corpo = (await pedido.postDataBuffer()) ?? Buffer.alloc(0);
    pedidos.push({
      metodo: pedido.method(),
      contentType: pedido.headers()["content-type"] ?? "",
      corpo,
    });

    const resposta = responder();
    if (resposta.tipo === "sucesso") {
      await rota.fulfill({
        status: 202,
        contentType: "application/json",
        body: JSON.stringify({ estado: "pendente" }),
      });
      return;
    }
    await rota.fulfill({
      status: resposta.estado,
      contentType: "application/json",
      headers: resposta.cabecalhos,
      body: JSON.stringify(resposta.corpo),
    });
  });

  return pedidos;
}

/**
 * Gera uma imagem JPEG a sério, **dentro da página** (um `<canvas>` a
 * `toBlob`) — é a única forma de provar que a redução correu num browser
 * de verdade, e não contra uma função fingida (16.5, ponto 3).
 */
export async function gerarImagemNaPagina(
  pagina: Page,
  opcoes: { largura: number; altura: number },
): Promise<Buffer> {
  const bytes = await pagina.evaluate(async ({ largura, altura }) => {
    const tela = document.createElement("canvas");
    tela.width = largura;
    tela.height = altura;
    const contexto = tela.getContext("2d");
    if (contexto === null) throw new Error("sem contexto 2d: não consegui gerar a fixtura");
    contexto.fillStyle = "#783050";
    contexto.fillRect(0, 0, largura, altura);
    // Uma marca visual simples, para a imagem não ser um bloco perfeitamente
    // uniforme (algumas APIs de redimensionamento tratam blocos sólidos de
    // forma especial).
    contexto.fillStyle = "#d4af37";
    contexto.fillRect(0, 0, largura / 4, altura / 4);

    const blob = await new Promise<Blob | null>((resolver) => {
      tela.toBlob((b) => resolver(b), "image/jpeg", 0.8);
    });
    if (blob === null) throw new Error("toBlob devolveu null: não consegui gerar a fixtura");
    const buffer = await blob.arrayBuffer();
    return [...new Uint8Array(buffer)];
  }, opcoes);

  return Buffer.from(bytes);
}

